// =============================================================================
// Part spec
// =============================================================================

export type PartShape = 'box' | 'sphere' | 'cone' | 'cylinder';

/** A single model primitive, in unit-local space (Y up, +Z forward). */
export interface Part {
  shape: PartShape;
  /** RGB 0..1 (already converted from the source 0xRRGGBB). */
  color: [number, number, number];
  /** Local offset. */
  pos: [number, number, number];
  /** Local size — for box: [w,h,d]; sphere: [d,d,d]; cone/cyl: [d,h,d]. */
  scale: [number, number, number];
  /** Euler XYZ radians (applied as Z*Y*X via quats below). */
  rot?: [number, number, number];
  /** Emissive accent (glow) — skips lighting tint metalness, brightens color. */
  emissive?: boolean;
}

// hex 0xRRGGBB -> linear-ish [r,g,b] 0..1 (engine PBR baseColor is sRGB-ish here;
// the source fed raw hex to THREE which gamma-corrects — a plain /255 is close
// enough for the flat-shaded silhouette look and matches terrain/env tinting).
function rgb(hex: number): [number, number, number] {
  return [((hex >> 16) & 0xff) / 255, ((hex >> 8) & 0xff) / 255, (hex & 0xff) / 255];
}

// ── part builders (mirror source addPart with each THREE primitive) ──────────
function box(color: number | [number, number, number], pos: [number, number, number], size: [number, number, number], rot?: [number, number, number], emissive = false): Part {
  return { shape: 'box', color: Array.isArray(color) ? color : rgb(color), pos, scale: size, rot, emissive };
}
function sphere(color: number | [number, number, number], pos: [number, number, number], r: number, scale?: [number, number, number], rot?: [number, number, number], emissive = false): Part {
  const s: [number, number, number] = scale ? [2 * r * scale[0], 2 * r * scale[1], 2 * r * scale[2]] : [2 * r, 2 * r, 2 * r];
  return { shape: 'sphere', color: Array.isArray(color) ? color : rgb(color), pos, scale: s, rot, emissive };
}
function cone(color: number | [number, number, number], pos: [number, number, number], r: number, h: number, rot?: [number, number, number], emissive = false): Part {
  return { shape: 'cone', color: Array.isArray(color) ? color : rgb(color), pos, scale: [2 * r, h, 2 * r], rot, emissive };
}
function cyl(color: number | [number, number, number], pos: [number, number, number], r: number, h: number, rot?: [number, number, number], emissive = false): Part {
  return { shape: 'cylinder', color: Array.isArray(color) ? color : rgb(color), pos, scale: [2 * r, h, 2 * r], rot, emissive };
}

// =============================================================================
// Shared primitive meshes (built once, reused by every part of every unit)
// =============================================================================

export interface UnitPrimitives {
  box: Handle<'MeshAsset', 'shared'>;
  sphere: Handle<'MeshAsset', 'shared'>;
  cone: Handle<'MeshAsset', 'shared'>;
  cylinder: Handle<'MeshAsset', 'shared'>;
}

/**
 * Build + cache the 4 unit-sized primitive MeshAssets. Call ONCE per world in
 * bootstrap; pass the result to every `spawnUnitModel` so parts reuse them.
 */
export function makePrimitives(world: World): UnitPrimitives | null {
  const b = createBoxGeometry(1, 1, 1, 1, 1, 1);
  const s = createSphereGeometry(0.5, 12, 8);
  const c = createConeGeometry(0.5, 1, 8);
  const cy = createCylinderGeometry(0.5, 0.5, 1, 8);
  if (!b.ok || !s.ok || !c.ok || !cy.ok) {
    console.error('[marscraft] unit primitive geometry build failed');
    return null;
  }
  return {
    box: world.allocSharedRef('MeshAsset', b.value as MeshAsset),
    sphere: world.allocSharedRef('MeshAsset', s.value as MeshAsset),
    cone: world.allocSharedRef('MeshAsset', c.value as MeshAsset),
    cylinder: world.allocSharedRef('MeshAsset', cy.value as MeshAsset),
  };
}

// =============================================================================
// Material tinting (cached per packed color so parts share handles)
// =============================================================================

/** Mints a tinted PBR material handle from an [r,g,b] (closes over base GUID). */
export type TintFn = (rgb: [number, number, number], opts?: { metallic?: number; roughness?: number }) => Handle<'MaterialAsset', 'shared'>;

const matCache = new Map<string, Handle<'MaterialAsset', 'shared'>>();

function partMaterial(tint: TintFn, color: [number, number, number], emissive: boolean): Handle<'MaterialAsset', 'shared'> {
  // emissive accents read brighter + flatter; lit parts get a little metal.
  const key = `${color[0].toFixed(3)},${color[1].toFixed(3)},${color[2].toFixed(3)},${emissive ? 1 : 0}`;
  const hit = matCache.get(key);
  if (hit) return hit;
  const c: [number, number, number] = emissive
    ? [Math.min(1, color[0] * 1.4 + 0.2), Math.min(1, color[1] * 1.4 + 0.2), Math.min(1, color[2] * 1.4 + 0.2)]
    : color;
  const m = tint(c, emissive ? { metallic: 0, roughness: 1 } : { metallic: 0.2, roughness: 0.7 });
  matCache.set(key, m);
  return m;
}

/** Reset the per-color material cache (call between worlds if reused). */
export function resetUnitMaterialCache(): void {
  matCache.clear();
}

// =============================================================================
// Spawn a composite model under a parent entity (approach A)
// =============================================================================

const _q = quat.create();

/**
 * Spawn every part of `def`'s composite model as a child entity of `parent`.
 * `factionColor` is the packed 0xRRGGBB player color used wherever the source
 * passed `playerColor`. Returns the spawned child entity handles.
 */
export function spawnUnitModel(
  world: World,
  parent: EntityHandle,
  def: UnitDef,
  factionColor: number,
  prims: UnitPrimitives,
  tint: TintFn,
): EntityHandle[] {
  const parts = (UNIT_PARTS[def.typeId] ?? fallbackParts)(def, factionColor);
  // Uniform model scale: source model is authored ~unit-height ~1; def.modelSize
  // is the in-world render size. We scale the whole composite by modelSize.
  const k = def.modelSize;
  const children: EntityHandle[] = [];
  for (const p of parts) {
    const mesh =
      p.shape === 'box' ? prims.box :
      p.shape === 'sphere' ? prims.sphere :
      p.shape === 'cone' ? prims.cone :
      prims.cylinder;
    const mat = partMaterial(tint, p.color, p.emissive ?? false);
    // THREE's default Euler order is 'XYZ'; match it so ported rotations align.
    if (p.rot) quat.fromEuler(_q, p.rot[0], p.rot[1], p.rot[2], 'XYZ');
    const res = world.spawn(
      {
        component: Transform,
        data: {
          pos: [p.pos[0] * k, p.pos[1] * k, p.pos[2] * k],
          quat: p.rot ? [_q[0], _q[1], _q[2], _q[3]] : [0, 0, 0, 1],
          scale: [p.scale[0] * k, p.scale[1] * k, p.scale[2] * k],
        },
      },
      { component: MeshFilter, data: { assetHandle: mesh } },
      { component: MeshRenderer, data: { materials: [mat] } },
      { component: ChildOf, data: { parent } },
    );
    if (res.ok) children.push(res.value);
  }
  return children;
}

