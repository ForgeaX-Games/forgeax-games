// =============================================================================
// Fallback: recognizable silhouette by category / size / race
// =============================================================================
// Used for units without a hand-ported part list (most buildings + special
// units). Keeps a clear body + race-flavored accent so every unit still renders
// as a distinct, readable shape rather than a bare cube.

function fallbackParts(def: UnitDef, color: number): Part[] {
  const parts: Part[] = [];
  const sizeK = def.unitSize === 'large' ? 1.0 : def.unitSize === 'medium' ? 0.7 : 0.5;

  if (def.category === 'building') {
    // Buildings: chunky base + a race-distinct topper.
    parts.push(box(color, [0, 0.25, 0], [1.0, 0.5, 1.0]));
    parts.push(box(C_GRAY, [0, 0.55, 0], [0.7, 0.2, 0.7]));
    if (def.race === 'protoss') {
      parts.push(cone(C_GOLD, [0, 0.85, 0], 0.25, 0.5));
      parts.push(sphere(C_BLUEGLOW, [0, 0.95, 0], 0.1, undefined, undefined, true));
    } else if (def.race === 'zerg') {
      parts.push(sphere(C_CARAPACE, [0, 0.7, 0], 0.4, [1, 0.7, 1]));
      parts.push(cone(C_BONE, [0, 1.0, 0], 0.1, 0.4));
    } else {
      parts.push(box(0xffaa00, [0, 0.75, 0], [0.3, 0.15, 0.3], undefined, true));
      parts.push(cyl(C_GRAY, [0.35, 0.6, 0.35], 0.06, 0.5));
    }
    return parts;
  }

  // Mobile units: body + head + race accent + (ground) legs.
  if (def.race === 'zerg') {
    parts.push(sphere(color, [0, 0.1, 0], 0.35 * sizeK, [1, 0.8, 1.2]));
    parts.push(box(C_CARAPACE, [0, 0.35 * sizeK, 0], [0.4 * sizeK, 0.12, 0.4 * sizeK]));
    parts.push(cone(C_BONE, [0, 0.5 * sizeK, -0.05], 0.06, 0.3 * sizeK, [-0.4, 0, 0]));
  } else if (def.race === 'protoss') {
    parts.push(box(color, [0, 0, 0], [0.45 * sizeK, 0.55 * sizeK, 0.35 * sizeK]));
    parts.push(sphere(color, [0, 0.4 * sizeK, 0], 0.16 * sizeK));
    parts.push(cone(C_GOLD, [0, 0.6 * sizeK, 0], 0.04, 0.25 * sizeK));
    parts.push(sphere(C_BLUEGLOW, [0, 0.4 * sizeK, 0.15], 0.05, undefined, undefined, true));
  } else {
    parts.push(box(color, [0, 0, 0], [0.45 * sizeK, 0.55 * sizeK, 0.35 * sizeK]));
    parts.push(sphere(color, [0, 0.4 * sizeK, 0], 0.16 * sizeK));
    parts.push(sphere(C_BLUEGLOW, [0, 0.4 * sizeK, 0.15], 0.08, undefined, undefined, true));
  }
  if (def.isGround) {
    parts.push(box(color, [-0.12 * sizeK, -0.4 * sizeK, 0], [0.12 * sizeK, 0.3 * sizeK, 0.12 * sizeK]));
    parts.push(box(color, [0.12 * sizeK, -0.4 * sizeK, 0], [0.12 * sizeK, 0.3 * sizeK, 0.12 * sizeK]));
  }
  return parts;
}

