/**
 * MarsCraft -> forgeax-engine — unit definitions table (Milestone M3)
 * =============================================================================
 * Faithful port of the Three.js source `web/data/units.ts` (2346 LOC).
 *
 * 3 races (Terran / Zerg / Protoss) x workers + combat units + buildings +
 * special units. Every stats / cost / vision / attack / ability / model field
 * from the source is preserved verbatim — these feed the M2 components (via the
 * factory) and later milestones (combat / economy / buildings / abilities).
 *
 * The only adaptation vs. source:
 *   - `RANGE_SCALE` (source `data/balance.ts`, = 1.84) is inlined here so this
 *     table compiles standalone (balance.ts is a cross-cutting data table that
 *     M6/M8/M9 will port in full; only the one constant the unit table needs is
 *     carried here).
 *   - `getUnitName(typeId)` i18n lookup (source `data/i18nHelper`) is NOT
 *     ported here; `displayName` already carries the human-readable label and
 *     the factory uses it directly. (M12 will wire real i18n.)
 *
 * The model spec the factory + unit-models consume is the unit `typeId` +
 * `modelSize` (the composite part-lists live in `src/world/unit-models.ts`,
 * keyed by typeId — exactly as the source `MODEL_CREATORS` map is keyed).
 */

/**
 * Range/vision scale — SC-original grid cells x RANGE_SCALE = world units.
 * Source SSOT: `web/data/balance.ts` (= 1.84). Inlined (see header).
 */
export const RANGE_SCALE = 1.84;

export type UnitCategory = 'worker' | 'infantry' | 'vehicle' | 'building';
/** Legacy size class — model/collision only, no longer affects damage. */
export type UnitSize = 'small' | 'medium' | 'large';
export type RaceType = 'terran' | 'protoss' | 'zerg';

/**
 * Combat type — triangle counter system.
 *   armored > bio       (steel crushes flesh)
 *   bio     > psionic   (primal minds resist psi)
 *   psionic > armored   (psi dissolves armor)
 * Neutral (100% both ways): void (transdimensional), structure (buildings).
 */
export type CombatType = 'bio' | 'armored' | 'psionic' | 'void' | 'structure';

/** Form definition — a complete stat override for a unit in a given form. */
export interface FormDef {
  formId: string;
  displayName: string;
  /** Weapon id used in this form (null = cannot attack). */
  weaponId: string | null;
  hp?: number;
  armor?: number;
  shield?: number;
  shieldArmor?: number;
  speed?: number; // 0 = immobile
  turnRate?: number;
  moveType?: 'ground' | 'air';
  combatType?: CombatType;
  unitSize?: UnitSize;
  isMechanical?: boolean;
  modelId?: string;
  modelSize?: number;
  selectionRadius?: number;
  /** Ability list in this form (replaces the base list). */
  abilityIds?: string[];
  /** Trigger condition to exit this form. */
  exitTrigger?: {
    /** Auto-exit this form when the named ability's sustained phase completes. */
    onAbilityComplete?: string;
  };
  applyCloakOnEnter?: boolean;
  removeCloakOnEnter?: boolean;
  visionRangeGrid?: number;
}

export interface UnitDef {
  typeId: string;
  displayName: string;
  /** Unit description (tooltip). */
  description?: string;
  race: RaceType;
  category: UnitCategory;
  unitSize: UnitSize;
  /** Combat type (triangle: bio/armored/psionic, neutral: void/structure). */
  combatType: CombatType;

  hp: number;
  armor: number;
  shield: number;
  shieldArmor: number;

  speed: number; // world units / sec
  turnRate: number; // radians / sec

  /** SC-original grid cells, x RANGE_SCALE = world units. */
  visionRangeGrid: number;
  /** World units (auto-computed). */
  visionRange: number;

  selectionRadius: number;
  selectionPriority: number;

  /** Weapon id (-> weapons.ts). */
  weaponId: string | null;

  /** Model render size. */
  modelSize: number;

  /** Ground unit? */
  isGround: boolean;

  // ---- economy ----
  mineralCost: number;
  gasCost: number;
  supplyCost: number;
  supplyProvide: number;
  buildTime: number;
  isMechanical: boolean;
  canRepair?: boolean;
  canAssistBuild?: boolean;
  canMorphTo?: string[];
  morphCost?: { mineral: number; gas: number };
  trainCount?: number;
  trainPrerequisite?: string[];

  garrisonSize?: number;
  transportCapacity?: number;
  transportCrashDamage?: number;
  transportCanAttack?: boolean;
  transportUiColumns?: number;
  transportRightClickToLoad?: boolean;
  transportRightClickToBoard?: boolean;
  transportUnloadMode?: 'instant' | 'queued';
  transportUnloadInterval?: number;
  transportRequiredUpgrade?: string;
  transportEjectRadius?: number;

  // ---- energy ----
  energyMax?: number;
  energyRegen?: number;
  energyStartPercent?: number;

  // ---- forms ----
  forms?: FormDef[];
  formSwitchTime?: number;
}

/** Build a UnitDef, filling economy defaults + deriving visionRange. */
function def(
  partial: Omit<
    UnitDef,
    'visionRange' | 'mineralCost' | 'gasCost' | 'supplyCost' | 'supplyProvide' | 'buildTime' | 'isMechanical'
  > &
    Partial<
      Pick<UnitDef, 'mineralCost' | 'gasCost' | 'supplyCost' | 'supplyProvide' | 'buildTime' | 'isMechanical'>
    >,
): UnitDef {
  return {
    mineralCost: 0,
    gasCost: 0,
    supplyCost: 0,
    supplyProvide: 0,
    buildTime: 0,
    isMechanical: false,
    ...partial,
    visionRange: partial.visionRangeGrid * RANGE_SCALE,
  };
}

