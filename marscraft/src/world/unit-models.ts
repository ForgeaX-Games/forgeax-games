/**
 * MarsCraft -> forgeax-engine — composite unit models (Milestone M3)
 * =============================================================================
 * Port of the Three.js source `web/engine/UnitModels.ts` (3833 LOC, ~80
 * `THREE.Group` builders). forgeax has no THREE.Group, so we use **approach (A)
 * multi-entity models** (see the task brief + ENGINE-API-CHEATSHEET "Custom
 * geometry"):
 *
 *   - the unit's parent entity carries the engine `Transform` (world pos);
 *   - every model part is a **child entity** with engine `ChildOf(parent)` +
 *     its own local `Transform` (offset / scale / rotation) + `MeshFilter`
 *     (one of FOUR shared unit-primitive MeshAssets — box / sphere / cone /
 *     cylinder, built once by `makePrimitives` and reused across ALL parts of
 *     ALL units) + `MeshRenderer` (a per-color tinted material, cached).
 *
 * The engine's auto-registered `propagateTransforms` system composes each
 * child's local Transform with the parent's into a world matrix every frame, so
 * the composite moves/rotates as one and parts remain individually animatable
 * (forms / turrets in later milestones).
 *
 * ── Source geometry -> forgeax mapping ───────────────────────────────────────
 * The source builds parts with `addPart(group, geo, material, pos, scale?, rot?)`
 * where `geo` is a THREE primitive:
 *   BoxGeometry(w,h,d)            -> box(pos, [w,h,d], rot?)
 *   SphereGeometry(r,...)         -> sphere(pos, r, rot?)        (unit sphere d=1)
 *   ConeGeometry(r,h,seg)         -> cone(pos, r, h, rot?)       (unit cone d=1,h=1)
 *   CylinderGeometry(rT,rB,h,seg) -> cyl(pos, max(rT,rB), h, rot?)
 * The 4 shared primitives are UNIT-sized (box 1x1x1; sphere d=1; cone d=1,h=1;
 * cylinder d=1,h=1), so a part's source dimensions become its child Transform
 * scale. Source per-part rotations (incl. baked-in nested-group offsets/rots)
 * are flattened into each part's local rot/pos — faithful for static models.
 *
 * ── Coverage / simplifications ───────────────────────────────────────────────
 * Faithful per-unit part lists are ported for the M3 test army + a spread of
 * each race (see UNIT_PARTS). The remaining units fall back to a recognizable
 * silhouette generated by `fallbackParts(def)` keyed on category/size/race
 * (a body + race-flavored accents). Units whose source model relied on
 * animation rigs / nested groups beyond a static silhouette and were thus
 * simplified are noted in the port report (e.g. Siege Tank — static turret, no
 * deploy-pose rig; organic Zerg leg sub-groups — top-level legs only).
 */

